CREATE TABLE audit_history (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recorded_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    database_actor text NOT NULL DEFAULT current_user,
    workflow_actor text,
    resource text NOT NULL,
    record_key text,
    operation text NOT NULL CHECK (operation IN ('INSERT', 'UPDATE', 'DELETE')),
    changed_fields text[] NOT NULL,
    before_values jsonb NOT NULL,
    after_values jsonb NOT NULL,
    previous_status text,
    current_status text
);

CREATE FUNCTION record_smartcity_change() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE
    old_row jsonb := CASE WHEN TG_OP <> 'INSERT' THEN to_jsonb(OLD) ELSE '{}'::jsonb END;
    new_row jsonb := CASE WHEN TG_OP <> 'DELETE' THEN to_jsonb(NEW) ELSE '{}'::jsonb END;
    row_data jsonb := old_row || new_row;
    changed text[];
    visible_fields text[] := CASE TG_TABLE_NAME
        WHEN 'tourism_places' THEN ARRAY['category','opening_hours','rating']
        WHEN 'educational_institutions' THEN ARRAY['institution_type']
        WHEN 'cities' THEN ARRAY['name','description','country','latitude','longitude']
        WHEN 'places' THEN ARRAY['name','description','address','latitude','longitude','city_id']
        WHEN 'companies' THEN ARRAY['name','title','description','city','country','region','latitude','longitude']
        WHEN 'jobs' THEN ARRAY['title','company_id','employment_type','salary','application_deadline']
        WHEN 'sport_events' THEN ARRAY['title','event_date','venue_id','slot_id','ticket_price','ticket_capacity','reserved_tickets']
        WHEN 'venues' THEN ARRAY['venue_type','capacity']
        WHEN 'venue_slots' THEN ARRAY['venue_id','starts_at','ends_at']
        WHEN 'business_news' THEN ARRAY['company_id','title','category','published_at']
        WHEN 'bookings' THEN ARRAY['event_id','venue_id','quantity','unit_price','status']
        WHEN 'job_applications' THEN ARRAY['job_id','status']
        WHEN 'favourites' THEN ARRAY['tourism_id','education_id','sports_id','jobs_id','business_id','news_id']
        ELSE ARRAY[]::text[]
    END;
    before_values jsonb;
    after_values jsonb;
BEGIN
    SELECT coalesce(array_agg(key ORDER BY key), ARRAY[]::text[]) INTO changed
    FROM jsonb_object_keys(row_data) AS f(key)
    WHERE old_row -> key IS DISTINCT FROM new_row -> key;
    IF cardinality(changed) = 0 THEN RETURN NULL; END IF;

    SELECT coalesce(jsonb_object_agg(e.key, e.value), '{}'::jsonb) INTO before_values
    FROM jsonb_each(old_row) e WHERE e.key = ANY(changed) AND e.key = ANY(visible_fields);
    SELECT coalesce(jsonb_object_agg(e.key, e.value), '{}'::jsonb) INTO after_values
    FROM jsonb_each(new_row) e WHERE e.key = ANY(changed) AND e.key = ANY(visible_fields);

    EXECUTE format('INSERT INTO %I.audit_history
        (workflow_actor, resource, record_key, operation, changed_fields, before_values, after_values, previous_status, current_status)
        VALUES ($1,$2,$3,$4,$5,$6,$7,$8,$9)', TG_TABLE_SCHEMA)
    USING nullif(current_setting('smartcity.workflow_actor', true), ''), TG_TABLE_NAME,
          coalesce(row_data ->> 'id', row_data ->> 'users_id', row_data ->> 'cv_id', row_data ->> 'company_id'),
          TG_OP, changed, before_values, after_values,
          CASE WHEN TG_TABLE_NAME IN ('bookings','job_applications') THEN old_row ->> 'status' END,
          CASE WHEN TG_TABLE_NAME IN ('bookings','job_applications') THEN new_row ->> 'status' END;
    RETURN NULL;
END
$$;

DO $$
DECLARE
    resource text;
BEGIN
    FOREACH resource IN ARRAY ARRAY[
        'admins','bookings','cities','companies','company_specialties','cv_key_words','cv_skills','cvs',
        'educational_institutions','job_applications','jobs','monitorings','online_sessions','places',
        'sport_events','studentses','tokens','tourism_places','touristses','users_roles','userses',
        'venues','venue_slots','business_news','favourites'
    ] LOOP
        EXECUTE format('CREATE TRIGGER smartcity_audit AFTER INSERT OR UPDATE OR DELETE ON %I
                        FOR EACH ROW EXECUTE FUNCTION record_smartcity_change()', resource);
    END LOOP;
END
$$;
