CREATE TABLE admins (
    authorization_level integer NOT NULL,
    adminid bigint NOT NULL,
    id bigint GENERATED BY DEFAULT AS IDENTITY
);

CREATE TABLE bookings (
    booking_date timestamp(6) without time zone NOT NULL,
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    users_id bigint,
    venue_id bigint,
    status character varying(255) NOT NULL,
    CONSTRAINT bookings_status_check CHECK (((status)::text = ANY ((ARRAY['PENDING'::character varying, 'CONFIRMED'::character varying, 'CANCELLED'::character varying])::text[])))
);

CREATE TABLE cities (
    latitude double precision NOT NULL,
    longitude double precision NOT NULL,
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    country character varying(255) NOT NULL,
    description character varying(255) NOT NULL,
    name character varying(255) NOT NULL
);

CREATE TABLE companies (
