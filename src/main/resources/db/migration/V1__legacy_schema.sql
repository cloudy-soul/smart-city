CREATE TABLE job_applications (
    application_date timestamp(6) with time zone NOT NULL,
    c_v_id bigint,
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    job_id bigint,
    users_id bigint,
    status character varying(255) NOT NULL,
    CONSTRAINT job_applications_status_check CHECK (((status)::text = ANY ((ARRAY['PENDING'::character varying, 'ACCEPTED'::character varying, 'REJECTED'::character varying])::text[])))
);

CREATE TABLE jobs (
    salary double precision NOT NULL,
    company_id bigint,
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    description character varying(255) NOT NULL,
    employment_type character varying(255) NOT NULL,
    industry character varying(255) NOT NULL,
    title character varying(255) NOT NULL
);

CREATE TABLE monitorings (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    "timestamp" timestamp(6) with time zone NOT NULL,
    record_type character varying(255) NOT NULL,
    source character varying(255) NOT NULL,
    status character varying(255) NOT NULL
);

CREATE TABLE online_sessions (
    altitude double precision,
    authenticated boolean NOT NULL,
    longitude double precision,
    cookies_id bigint NOT NULL,
    id bigint GENERATED BY DEFAULT AS IDENTITY,
