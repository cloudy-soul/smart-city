-- Reuse existing matching slots first. Duplicate events at the same venue and
-- time need an explicit scheduling decision in Admin.
WITH candidates AS (
    SELECT e.venue_id, e.event_date, min(e.id) AS event_id
    FROM sport_events e WHERE e.slot_id IS NULL AND isfinite(e.event_date)
          AND e.ticket_price >= 0 AND e.ticket_price < 'Infinity'::float8
    GROUP BY e.venue_id, e.event_date
)
UPDATE sport_events e SET slot_id = s.id
FROM candidates c JOIN venue_slots s ON s.venue_id = c.venue_id AND s.starts_at = c.event_date
WHERE e.id = c.event_id
  AND NOT EXISTS (SELECT 1 FROM sport_events assigned WHERE assigned.slot_id = s.id);

-- Preserve published event times. Only add a one-hour slot if neither the
-- venue calendar nor the next event uses any part of that hour.
INSERT INTO venue_slots(venue_id, starts_at, ends_at)
SELECT e.venue_id, e.event_date, e.event_date + interval '1 hour'
FROM sport_events e
WHERE e.slot_id IS NULL AND isfinite(e.event_date)
  AND e.ticket_price >= 0 AND e.ticket_price < 'Infinity'::float8
  AND NOT EXISTS (SELECT 1 FROM sport_events earlier
                  WHERE earlier.venue_id = e.venue_id AND earlier.id < e.id
                    AND earlier.event_date = e.event_date)
  AND NOT EXISTS (SELECT 1 FROM sport_events next_event
                  WHERE next_event.venue_id = e.venue_id AND next_event.event_date > e.event_date
                    AND next_event.event_date < e.event_date + interval '1 hour')
  AND NOT EXISTS (SELECT 1 FROM venue_slots s WHERE s.venue_id = e.venue_id
                  AND s.starts_at < e.event_date + interval '1 hour' AND s.ends_at > e.event_date);

UPDATE sport_events e SET slot_id = s.id
FROM venue_slots s
WHERE e.slot_id IS NULL AND e.venue_id = s.venue_id AND e.event_date = s.starts_at
  AND e.ticket_price >= 0 AND e.ticket_price < 'Infinity'::float8
  AND e.id = (SELECT min(peer.id) FROM sport_events peer WHERE peer.venue_id = e.venue_id AND peer.event_date = e.event_date)
  AND NOT EXISTS (SELECT 1 FROM sport_events assigned WHERE assigned.slot_id = s.id);

-- Leaves legacy sales closed until Admin explicitly sets a verified capacity.
CREATE TABLE favourites (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL REFERENCES userses(id) ON DELETE CASCADE,
    tourism_id bigint REFERENCES tourism_places(id) ON DELETE CASCADE,
    education_id bigint REFERENCES educational_institutions(id) ON DELETE CASCADE,
    sports_id bigint REFERENCES sport_events(id) ON DELETE CASCADE,
    jobs_id bigint REFERENCES jobs(id) ON DELETE CASCADE,
    business_id bigint REFERENCES companies(id) ON DELETE CASCADE,
    news_id bigint REFERENCES business_news(id) ON DELETE CASCADE,
    CHECK (num_nonnulls(tourism_id, education_id, sports_id, jobs_id, business_id, news_id) = 1)
);
CREATE UNIQUE INDEX favourites_tourism_unique ON favourites(user_id, tourism_id) WHERE tourism_id IS NOT NULL;
CREATE UNIQUE INDEX favourites_education_unique ON favourites(user_id, education_id) WHERE education_id IS NOT NULL;
CREATE UNIQUE INDEX favourites_sports_unique ON favourites(user_id, sports_id) WHERE sports_id IS NOT NULL;
CREATE UNIQUE INDEX favourites_jobs_unique ON favourites(user_id, jobs_id) WHERE jobs_id IS NOT NULL;
CREATE UNIQUE INDEX favourites_business_unique ON favourites(user_id, business_id) WHERE business_id IS NOT NULL;
CREATE UNIQUE INDEX favourites_news_unique ON favourites(user_id, news_id) WHERE news_id IS NOT NULL;
