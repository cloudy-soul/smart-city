CREATE TABLE venue_slots (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    venue_id bigint NOT NULL REFERENCES venues(id),
    starts_at timestamp NOT NULL,
    ends_at timestamp NOT NULL CHECK (ends_at > starts_at),
    CONSTRAINT venue_slots_venue_start_unique UNIQUE (venue_id, starts_at),
    CONSTRAINT venue_slots_id_venue_unique UNIQUE (id, venue_id)
);

ALTER TABLE sport_events
    ADD COLUMN slot_id bigint UNIQUE,
    ADD COLUMN ticket_capacity integer NOT NULL DEFAULT 0 CHECK (ticket_capacity >= 0),
    ADD COLUMN reserved_tickets integer NOT NULL DEFAULT 0,
    ADD CONSTRAINT event_slot_venue_fk FOREIGN KEY (slot_id, venue_id) REFERENCES venue_slots(id, venue_id),
    ADD CONSTRAINT event_inventory_check CHECK (reserved_tickets BETWEEN 0 AND ticket_capacity),
    ADD CONSTRAINT event_price_check CHECK (ticket_price >= 0 AND ticket_price < 'Infinity'::float8) NOT VALID;

ALTER TABLE bookings
    ADD COLUMN event_id bigint REFERENCES sport_events(id),
    ADD COLUMN quantity integer NOT NULL DEFAULT 1 CHECK (quantity > 0),
    ADD COLUMN unit_price numeric(12,2) NOT NULL DEFAULT 0 CHECK (unit_price >= 0),
    ADD CONSTRAINT booking_event_user_check CHECK (event_id IS NULL OR users_id IS NOT NULL);

ALTER TABLE jobs
    ADD COLUMN application_deadline date,
    ADD COLUMN requirements varchar(2000) NOT NULL DEFAULT '';

ALTER TABLE cvs ADD COLUMN owner_id bigint REFERENCES userses(id);
ALTER TABLE cvs ADD CONSTRAINT cvs_id_owner_unique UNIQUE (id, owner_id);
ALTER TABLE job_applications
    ADD COLUMN cover_note varchar(2000) NOT NULL DEFAULT '',
    ADD COLUMN sample_submission boolean NOT NULL DEFAULT false,
    ADD CONSTRAINT submission_links_check CHECK (NOT sample_submission OR
        (job_id IS NOT NULL AND users_id IS NOT NULL AND c_v_id IS NOT NULL)),
    ADD COLUMN sample_cv_owner_id bigint GENERATED ALWAYS AS
        (CASE WHEN sample_submission THEN users_id END) STORED,
    ADD CONSTRAINT submission_cv_owner_fk FOREIGN KEY (c_v_id, sample_cv_owner_id) REFERENCES cvs(id, owner_id);
CREATE UNIQUE INDEX job_applications_sample_unique ON job_applications(job_id, users_id) WHERE sample_submission;

CREATE TABLE business_news (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id bigint NOT NULL REFERENCES companies(id),
    title varchar(255) NOT NULL,
    body varchar(4000) NOT NULL,
    published_at timestamp with time zone,
    CONSTRAINT business_news_company_title_unique UNIQUE (company_id, title)
);

ALTER TABLE tokens ADD CONSTRAINT token_expiry_after_creation
    CHECK (expiration_date_time >= creation_date) NOT VALID;
